#!/usr/bin/env python3
"""Turn SELinux AVC denials into device sepolicy rules.

Reads `dmesg` / `logcat` output (a file, several files, or stdin) and emits one
`allow` rule per (source domain, target type, object class), with the denied
permissions merged. Nothing outside the standard library is used, so this runs
on any host without an AOSP checkout.

    adb shell dmesg > avc.log
    python3 sepolicy/audit2te.py avc.log --out-dir sepolicy/vendor

Denials that were only logged because the domain is still permissive
(`permissive=1`) are marked with a comment; they are the ones that will bite
once the domain is switched to enforcing.

By default a rule is only emitted for enforcing denials. Use
`--include-permissive` to also get the ones that only appeared while a domain
was permissive.
"""

import argparse
import os
import re
import sys
from collections import defaultdict

# avc: denied { read write } for pid=1589 comm="system_server" name="foo"
#   dev="tmpfs" ino=1 scontext=u:r:system_server:s0
#   tcontext=u:object_r:vendor_foo:s0 tclass=file permissive=0
AVC_RE = re.compile(
    r"avc:\s+denied\s+\{(?P<perms>[^}]*)\}\s+for\s+(?P<info>.*?)"
    r"scontext=(?P<scontext>\S+)\s+tcontext=(?P<tcontext>\S+)\s+"
    r"tclass=(?P<tclass>\S+)(?:\s+permissive=(?P<permissive>\d))?"
)
PATH_RE = re.compile(r'\bpath="([^"]+)"')
NAME_RE = re.compile(r'\bname="([^"]+)"')
TYPE_RE = re.compile(r"type=1400 audit\([^)]*\):\s*")


def parse_domain(scontext):
    """u:r:foo_bar:s0[:c123,c456] -> foo_bar"""
    parts = scontext.split(":")
    return parts[2] if len(parts) > 2 else scontext


def parse_type(tcontext):
    """u:object_r:foo_bar:s0 -> foo_bar"""
    parts = tcontext.split(":")
    return parts[2] if len(parts) > 2 else tcontext


def collect(paths):
    rules = defaultdict(lambda: {"perms": set(), "count": 0,
                                 "permissive": set(), "hint": None})
    for path in paths:
        try:
            handle = sys.stdin if path == "-" else open(path, "r",
                                                         errors="replace")
        except OSError as exc:
            sys.exit(f"cannot read {path}: {exc}")
        with handle:
            for line in handle:
                line = TYPE_RE.sub("", line)
                match = AVC_RE.search(line)
                if not match:
                    continue
                domain = parse_domain(match.group("scontext"))
                target = parse_type(match.group("tcontext"))
                tclass = match.group("tclass")
                key = (domain, target, tclass)
                entry = rules[key]
                entry["perms"].update(match.group("perms").split())
                entry["count"] += 1
                permissive = match.group("permissive")
                if permissive is not None:
                    entry["permissive"].add(permissive)
                if entry["hint"] is None:
                    hint = PATH_RE.search(line) or NAME_RE.search(line)
                    if hint:
                        entry["hint"] = hint.group(1)
    return rules


def render(rules, include_permissive):
    by_domain = defaultdict(list)
    skipped = 0
    for (domain, target, tclass), entry in sorted(rules.items()):
        only_permissive = entry["permissive"] == {"1"}
        if only_permissive and not include_permissive:
            skipped += 1
            continue
        perms = " ".join(sorted(entry["perms"]))
        comment = f"# {entry['count']} denial(s)"
        if entry["hint"]:
            comment += f", e.g. {entry['hint']}"
        if only_permissive:
            comment += ", permissive domain only"
        by_domain[domain].append(
            f"{comment}\nallow {domain} {target}:{tclass} {{ {perms} }};"
        )
    return by_domain, skipped


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("logs", nargs="+",
                        help="dmesg/logcat dumps (use - for stdin)")
    parser.add_argument("--out-dir", metavar="DIR",
                        help="write one <domain>.te per domain into DIR")
    parser.add_argument("--include-permissive", action="store_true",
                        help="also emit rules seen only under a permissive domain")
    args = parser.parse_args()

    rules = collect(args.logs)
    if not rules:
        sys.exit("no 'avc: denied' lines found")

    by_domain, skipped = render(rules, args.include_permissive)

    if args.out_dir:
        os.makedirs(args.out_dir, exist_ok=True)
        for domain, blocks in by_domain.items():
            path = os.path.join(args.out_dir, f"{domain}.te")
            header = (
                "# Generated by sepolicy/audit2te.py from a permissive boot.\n"
                "# Keep the rules that matter and delete the rest: every allow\n"
                "# here is a hole, so tighten types before widening rules.\n\n"
            )
            with open(path, "w") as handle:
                handle.write(header + "\n\n".join(blocks) + "\n")
            print(f"{path}: {len(blocks)} rule(s)")
    else:
        for domain, blocks in by_domain.items():
            print(f"# ---- {domain}")
            print("\n\n".join(blocks))
            print()

    if skipped:
        print(f"{skipped} denial group(s) only seen in permissive domains "
              f"were skipped (use --include-permissive)", file=sys.stderr)


if __name__ == "__main__":
    main()
